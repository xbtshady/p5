-- ============================================================================
--
-- 这一版只动数据，不动代码：清空旧标签是不可逆的，趁线上还停在 0.9 这个
-- 已知良好状态时单独做掉，出问题只可能是这条迁移本身，不必在新旧代码之间猜。
--
-- 【一】为什么加 ai_tips
--   AI 给的「下次这样拍」1-3 条，单开一列、不并进 note：
--     1. 要能分清哪句是自己写的、哪句是 AI 说的（AI 会错，这个区分以后有用）
--     2. 将来让 AI 重新分析时，新技巧不会和旧的叠在一起
--   页面/字段语义见 PRODUCT-1.0.md §四，编码方式见 ARCHITECTURE.md §4.2。
--
--   不加索引：ai_tips 从不参与筛选（筛选只按 tags），只跟着行一起取出来。
--   不需要动 GRANT / RLS：权限是按表授的，新列自动继承，隔离仍是 owner_id = auth.uid()。
--
-- 【二】为什么清空 tags 而不是迁移
--   0.7–0.9 的 tags 存的是自由标签（技法 6 个 / 题材 5 个），0.10 换成
--   「维度:值」的技术属性（如 镜头:中长焦）。两套体系并存会让筛选和探索区
--   都要多处理一种情况，而旧标签一共没几条、也不不可复用 —— 直接清掉。
--
--   ⚠️ 执行前实测（2026-09-18 17:30）全库仅此一行会被清掉：
--        id=8  title='test'  tags={构图,环境人像}   created_at=2026-09-18 16:40
--      也就是 0.8/0.9 联调时的测试残留。
--      照片（storage_path 指向的桶内文件）、标题、描述、created_at 全部不动。
--      清空后首页「探索」区会自然消失（无标签可列），属预期。
--
--   清完到写入口上线之间有个窗口：新增页还是旧的自由标签框，这期间录进去的
--   会是一条没有维度的裸标签。窗口只有一次部署那么长，不为它写兼容代码。
--
-- 应用（与前面几版一致：本环境没有 schema_migrations 表，迁移都是手动执行的）：
--   tcb db execute -e p5-d4g6dukvb86de1377 --sql "<本文件去掉注释后的两条语句>"
-- 已执行：2026-09-18 17:33，AffectedRows=1（就是上面那一行）
-- ============================================================================

ALTER TABLE public.photo_notes
  ADD COLUMN IF NOT EXISTS ai_tips TEXT[] NOT NULL DEFAULT '{}';

-- 旧自由标签退役：只清内容，不删列、不删索引 ——
-- photo_notes_tags_idx 下一版照样给「维度:值」用（仍是数组包含查询）。
UPDATE public.photo_notes
   SET tags = '{}'
 WHERE coalesce(array_length(tags, 1), 0) > 0;
